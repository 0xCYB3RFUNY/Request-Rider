package active

import (
	"fmt"
	"sort"
	"strings"
	"time"
)

// ReplayScript renders every proven finding of a run as one shell script that
// re-issues the requests.
//
// This is the last capability of the exploit side that a report carries, and it
// is the one that turns a report into something an operator can hand on: each
// finding already knows the exact request that produced it, and a script is just
// those requests in the order they should be re-run. Without it the curl commands
// live one per row in a table, which is fine to read and useless to execute.
//
// Two properties decide whether the script is worth having, and both are why this
// is generated rather than assembled:
//
//   - **It re-runs what the run actually proved.** Only findings with a proof and
//     a non-empty reproduction are emitted. A row whose impact was never
//     demonstrated has nothing to replay, and emitting it would put a command in
//     the script that reproduces the *request* and not the *defect* — a script
//     that returns 200 for six of its seven lines is worse than one with four.
//   - **It runs the commands as written, without rewriting them.** The command is
//     copied verbatim from the finding, so what executes is byte-for-byte what the
//     report claims reproduces the finding. Rewriting a curl into a "nicer" form
//     would break that link, and a PoC that has drifted from its proof is the one
//     artefact nobody checks.
//
// Every line is echoed before it runs, so the output is a transcript rather than a
// stream of response bodies the operator cannot attribute.
func ReplayScript(report Report, generatedAt time.Time) string {
	lines := []string{
		"#!/bin/sh",
		"# Generated by RequestRider active scanner.",
		"#",
		"# Replays every proven finding of one scan. Each command is copied verbatim",
		"# from the finding it belongs to, so what runs here is what the report says",
		"# reproduces it.",
		"#",
		fmt.Sprintf("# Target:   %s", report.Target),
		fmt.Sprintf("# Scan:     %s", report.Started.UTC().Format(time.RFC3339)),
		fmt.Sprintf("# Generated: %s", generatedAt.UTC().Format(time.RFC3339)),
		"",
		"set -u",
		"",
	}

	replayable := ReplayableFindings(report.Findings, report.Proofs)
	if len(replayable) == 0 {
		lines = append(lines,
			"# No finding in this run was both proven and replayable, so there is",
			"# nothing to execute. A scan that demonstrated no impact produces no",
			"# PoC on purpose: a script that returns 200 for every line and proves",
			"# nothing is a worse artefact than no script.",
		)
		return strings.Join(lines, "\n") + "\n"
	}

	lines = append(lines,
		fmt.Sprintf("# %d finding(s) to replay.", len(replayable)),
		"",
	)

	for index, finding := range replayable {
		lines = append(lines,
			fmt.Sprintf("# [%d/%d] %s", index+1, len(replayable), oneLine(finding.Title)),
			fmt.Sprintf("#   module:  %s", finding.Module),
			fmt.Sprintf("#   id:      %s", finding.ID),
			fmt.Sprintf("#   surface: %s %s%s", finding.Method, finding.Endpoint, paramSuffix(finding.Param)),
			fmt.Sprintf("#   impact:  %s", oneLine(finding.Evidence)),
			fmt.Sprintf("echo '--- [%d/%d] %s (%s)'", index+1, len(replayable), finding.Module, finding.ID),
			finding.PoCCurl,
			"echo",
			"",
		)
	}
	return strings.Join(lines, "\n") + "\n"
}

// ReplayableFindings returns the findings a replay script can execute.
//
// A finding qualifies on two conditions at once: the run demonstrated its impact
// (a proof exists for its ID, and that proof carries a command), and the finding
// carries a reproduction command of its own. Either alone is insufficient — a
// proof without a finding has nothing to emit, and a finding without a proof
// replays a request that was never shown to mean anything.
//
// Findings and proofs arrive as two lists because the detectors write them
// separately and a chain finding never has a proof of its own. Both are needed,
// and the ID is what joins them.
//
// The result is sorted by ID so two runs of the same target produce the same
// script, which is what makes the script diffable the same way the findings are.
func ReplayableFindings(findings []Finding, proofs []Proof) []Finding {
	proven := map[string]bool{}
	for _, proof := range proofs {
		if proof.Runnable == "" {
			continue
		}
		proven[proof.FindingID] = true
	}
	var out []Finding
	for _, finding := range findings {
		if finding.PoCCurl == "" {
			continue
		}
		if !proven[finding.ID] {
			continue
		}
		out = append(out, finding)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].ID < out[j].ID })
	return out
}

// paramSuffix renders a parameter name for a comment line, or nothing when the
// finding is not parameter-bound.
func paramSuffix(param string) string {
	param = strings.TrimSpace(param)
	if param == "" {
		return ""
	}
	return "  param=" + oneLine(param)
}

// oneLine collapses a value to a single line so it cannot break a comment.
//
// A template title or a matcher excerpt routinely carries a newline, and a
// newline inside a `#` comment silently ends that comment: the rest of the value
// lands in the script as code. That is the difference between a report that is
// merely untidy and one that executes a fragment of a target's response.
func oneLine(value string) string {
	replaced := strings.ReplaceAll(value, "\r\n", " ")
	replaced = strings.ReplaceAll(replaced, "\n", " ")
	replaced = strings.ReplaceAll(replaced, "\r", " ")
	if len(replaced) > 160 {
		replaced = replaced[:160] + "…"
	}
	return strings.TrimSpace(replaced)
}
