"""One-Click Reproducible PoC & Regression Packager (F10 ROADMAP)."""
from __future__ import annotations

import json
import shlex
from typing import Any


def _normalize_target(payload: dict[str, Any]) -> dict[str, Any]:
    """Extract normalized request & assertion metadata from an exchange, finding, or workflow."""
    exchange = payload.get("exchange") if isinstance(payload.get("exchange"), dict) else {}
    finding = payload.get("finding") if isinstance(payload.get("finding"), dict) else {}

    method = str(
        exchange.get("method")
        or finding.get("method")
        or payload.get("method")
        or "GET"
    ).upper()
    url = str(
        exchange.get("url")
        or finding.get("url")
        or finding.get("evidence_url")
        or payload.get("url")
        or ""
    ).strip()
    headers = exchange.get("request_headers") or exchange.get("headers") or payload.get("headers") or {}
    if not isinstance(headers, dict):
        headers = {}
    body = exchange.get("request_body")
    if body is None:
        body = exchange.get("body")
    if body is None:
        body = payload.get("body") or ""
    body_str = str(body)

    title = str(
        finding.get("title")
        or payload.get("title")
        or f"{method} {url or 'target'}"
    ).strip()
    evidence_marker = str(
        payload.get("evidence_marker")
        or finding.get("payload")
        or finding.get("evidence")
        or ""
    ).strip()
    # Keep evidence marker concise if it's a multi-line snippet
    if "\n" in evidence_marker:
        evidence_marker = evidence_marker.splitlines()[0].strip()
    if len(evidence_marker) > 120:
        evidence_marker = ""

    expected_status = payload.get("expected_status")
    if expected_status is None and exchange.get("status") is not None:
        expected_status = exchange.get("status")

    min_delay_ms = int(payload.get("min_delay_ms") or 0)
    proxy_url = str(payload.get("proxy_url") or "").strip()

    return {
        "title": title,
        "method": method,
        "url": url,
        "headers": {str(k): str(v) for k, v in headers.items() if str(k).lower() != "content-length"},
        "body": body_str,
        "expected_status": int(expected_status) if expected_status is not None and str(expected_status).isdigit() else None,
        "evidence_marker": evidence_marker,
        "min_delay_ms": min_delay_ms,
        "proxy_url": proxy_url,
    }


def generate_python_poc(spec: dict[str, Any]) -> str:
    """Generate a zero-dependency Python 3 stdlib reproducible PoC script."""
    return f'''#!/usr/bin/env python3
"""Reproducible PoC generated by Request-Rider: {spec["title"]}"""
import ssl
import sys
import time
import urllib.error
import urllib.request

TITLE = {spec["title"]!r}
METHOD = {spec["method"]!r}
URL = {spec["url"]!r}
HEADERS = {spec["headers"]!r}
BODY = {spec["body"]!r}
EXPECTED_STATUS = {spec["expected_status"]!r}
EVIDENCE_MARKER = {spec["evidence_marker"]!r}
MIN_DELAY_MS = {spec["min_delay_ms"]!r}
PROXY_URL = {spec["proxy_url"]!r}


def run_poc() -> int:
    ctx = ssl.create_default_context()
    ctx.check_hostname = False
    ctx.verify_mode = ssl.CERT_NONE

    handlers = [urllib.request.HTTPSHandler(context=ctx)]
    if PROXY_URL:
        handlers.append(urllib.request.ProxyHandler({{"http": PROXY_URL, "https": PROXY_URL}}))
    opener = urllib.request.build_opener(*handlers)

    data = BODY.encode("utf-8") if BODY and METHOD not in ("GET", "HEAD") else None
    req = urllib.request.Request(URL, data=data, headers=HEADERS, method=METHOD)

    started = time.monotonic()
    status = 0
    resp_body = ""
    try:
        with opener.open(req, timeout=15) as resp:
            status = resp.status
            resp_body = resp.read().decode("utf-8", errors="replace")
    except urllib.error.HTTPError as exc:
        status = exc.code
        resp_body = exc.read().decode("utf-8", errors="replace")
    except Exception as exc:
        print(f"[-] REQUEST ERROR: {{exc}}")
        return 2

    elapsed_ms = int((time.monotonic() - started) * 1000)
    status_ok = (EXPECTED_STATUS is None and 200 <= status < 400) or (status == EXPECTED_STATUS)
    marker_ok = (not EVIDENCE_MARKER) or (EVIDENCE_MARKER in resp_body)
    delay_ok = (MIN_DELAY_MS <= 0) or (elapsed_ms >= MIN_DELAY_MS)

    if status_ok and marker_ok and delay_ok:
        print(f"[+] VULNERABLE: {{TITLE}} (status={{status}}, elapsed={{elapsed_ms}}ms)")
        return 0

    print(f"[-] NOT REPRODUCED / PATCHED (status={{status}}, elapsed={{elapsed_ms}}ms)")
    return 1


if __name__ == "__main__":
    sys.exit(run_poc())
'''


def generate_playwright_poc(spec: dict[str, Any]) -> str:
    """Generate a Python + Playwright browser PoC with guaranteed cleanup."""
    return f'''#!/usr/bin/env python3
"""Playwright Browser PoC generated by Request-Rider: {spec["title"]}"""
import sys
from playwright.sync_api import sync_playwright

TITLE = {spec["title"]!r}
URL = {spec["url"]!r}
EVIDENCE_MARKER = {spec["evidence_marker"]!r}


def run_browser_poc() -> int:
    dialog_triggered = False
    with sync_playwright() as p:
        browser = p.firefox.launch(headless=True)
        try:
            context = browser.new_context(ignore_https_errors=True)
            page = context.new_page()

            def on_dialog(dialog):
                nonlocal dialog_triggered
                dialog_triggered = True
                dialog.dismiss()

            page.on("dialog", on_dialog)
            page.goto(URL, wait_until="domcontentloaded", timeout=15000)
            content = page.content()
            if dialog_triggered or (EVIDENCE_MARKER and EVIDENCE_MARKER in content):
                print(f"[+] VULNERABLE: {{TITLE}} (dialog={{dialog_triggered}})")
                return 0
            print("[-] NOT REPRODUCED / PATCHED")
            return 1
        finally:
            browser.close()


if __name__ == "__main__":
    sys.exit(run_browser_poc())
'''


def generate_go_poc(spec: dict[str, Any]) -> str:
    """Generate a standalone Go Race Condition / HTTP PoC."""
    hdr_lines = "\n".join(
        f'\t\t\treq.Header.Set({json.dumps(k)}, {json.dumps(v)})'
        for k, v in spec["headers"].items()
    )
    return f'''// Standalone Go PoC generated by Request-Rider: {spec["title"]}
package main

import (
\t"bytes"
\t"crypto/tls"
\t"fmt"
\t"net/http"
\t"os"
\t"sync"
\t"sync/atomic"
\t"time"
)

func main() {{
\tconst concurrency = 5
\tmethod := {json.dumps(spec["method"])}
\ttargetURL := {json.dumps(spec["url"])}
\tbody := []byte({json.dumps(spec["body"])})

\tclient := &http.Client{{
\t\tTimeout: 15 * time.Second,
\t\tTransport: &http.Transport{{
\t\t\tTLSClientConfig: &tls.Config{{InsecureSkipVerify: true}},
\t\t}},
\t}}

\tvar wg sync.WaitGroup
\tvar ok2xx int32
\tbarrier := make(chan struct{{}})

\tfor i := 0; i < concurrency; i++ {{
\t\twg.Add(1)
\t\tgo func(id int) {{
\t\t\tdefer wg.Done()
\t\t\t<-barrier
\t\t\treq, err := http.NewRequest(method, targetURL, bytes.NewReader(body))
\t\t\tif err != nil {{
\t\t\t\tfmt.Printf("[#%d] build error: %v\\n", id, err)
\t\t\t\treturn
\t\t\t}}
{hdr_lines}
\t\t\tresp, err := client.Do(req)
\t\t\tif err != nil {{
\t\t\t\tfmt.Printf("[#%d] request error: %v\\n", id, err)
\t\t\t\treturn
\t\t\t}}
\t\t\tdefer resp.Body.Close()
\t\t\tfmt.Printf("[#%d] status=%d\\n", id, resp.StatusCode)
\t\t\tif resp.StatusCode >= 200 && resp.StatusCode < 300 {{
\t\t\t\tatomic.AddInt32(&ok2xx, 1)
\t\t\t}}
\t\t}}(i)
\t}}

\tclose(barrier)
\twg.Wait()
\tif ok2xx > 0 {{
\t\tfmt.Printf("[+] VULNERABLE / SUCCEEDED (%d/%d 2xx)\\n", ok2xx, concurrency)
\t\tos.Exit(0)
\t}}
\tfmt.Println("[-] NOT REPRODUCED / PATCHED")
\tos.Exit(1)
}}
'''


def generate_curl_poc(spec: dict[str, Any]) -> str:
    """Generate a formatted cURL command."""
    parts = ["curl", "-i", "-s", "-k", "-X", shlex.quote(spec["method"])]
    if spec["proxy_url"]:
        parts.extend(["--proxy", shlex.quote(spec["proxy_url"])])
    for k, v in spec["headers"].items():
        parts.extend(["-H", shlex.quote(f"{k}: {v}")])
    if spec["body"]:
        parts.extend(["--data-binary", shlex.quote(spec["body"])])
    parts.append(shlex.quote(spec["url"]))
    return " \\\n  ".join(parts) + "\n"


def generate_poc(payload: dict[str, Any]) -> dict[str, str]:
    """Compile a reproducible PoC in python, playwright, go, or curl format."""
    fmt = str(payload.get("format") or "python").strip().lower()
    spec = _normalize_target(payload)
    if not spec["url"]:
        raise ValueError("url is required to generate PoC")

    if fmt == "python":
        return {"format": "python", "filename": "reproduce_poc.py", "code": generate_python_poc(spec)}
    if fmt == "playwright":
        return {"format": "playwright", "filename": "reproduce_browser_poc.py", "code": generate_playwright_poc(spec)}
    if fmt == "go":
        return {"format": "go", "filename": "reproduce_poc.go", "code": generate_go_poc(spec)}
    if fmt == "curl":
        return {"format": "curl", "filename": "reproduce_poc.sh", "code": generate_curl_poc(spec)}
    raise ValueError(f"unsupported PoC format: {fmt}")
