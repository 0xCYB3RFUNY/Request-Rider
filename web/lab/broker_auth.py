"""HMAC authentication for the Redis task/result envelopes.

Every envelope that crosses the broker is signed with a per-installation key
shared by Django and the Go engine (`RR_ENGINE_BROKER_KEY`). The signature is an
HMAC-SHA256 over the canonical JSON of the envelope, stored in the `sig` field.

Why this exists: the broker speaks no authentication — any local process can
`LPUSH` a well-formed envelope naming a live `task_id`, and `persist_engine_result`
used to trust it. A forged `completed` result moved a real workflow run forward on
attacker-supplied data; a forged task made the engine execute an action nobody
asked for. Shape validation (`engine_task_contract`) cannot tell a forged envelope
from a real one, because a forgery has the right shape by construction.

What this is not: it is not encryption (Redis still sees the payload), not a scope
gate (it says nothing about what the tools may do), and not a second source of
truth (the PostgreSQL row stays authoritative; the signature only says who wrote
the envelope).

Canonical form, shared with the Go side (`engine/broker_auth.go`): the envelope
without `sig`, keys sorted, compact separators, UTF-8, no HTML escaping. Both
sides must produce byte-identical input or every signature fails, so the exact
form is pinned by a cross-language test vector asserted in both test suites.
"""

import hashlib
import hmac
import json
import logging
import os

logger = logging.getLogger(__name__)

#: The shared per-installation key. 64 hex characters (32 bytes); generated by
#: `start.sh` into `data/run/broker_key` and exported to every service.
KEY_ENV = "RR_ENGINE_BROKER_KEY"

#: Field carrying the signature. Part of the v1 contract as an optional field:
#: validators ignore unknown fields, so old readers skip it and new readers verify.
SIG_FIELD = "sig"

_warned_compat: bool = False


def broker_key() -> bytes | None:
    """Return the shared key, or None when this install has none configured.

    A malformed value is treated as missing, loudly: refusing to boot on a bad
    key would brick a running stack over a typo, while silently using half a key
    would be worse than no key. Either way the operator is told.
    """
    global _warned_compat
    raw = os.environ.get(KEY_ENV, "").strip()
    if not raw:
        return None
    try:
        key = bytes.fromhex(raw)
    except ValueError:
        key = b""
    if len(key) < 16:
        if not _warned_compat:
            _warned_compat = True
            logger.error(
                "broker_auth_compat reason=%s_no_usable_key "
                "envelopes_are_unsigned_and_unverified",
                KEY_ENV,
            )
        return None
    return key


def signing_enabled() -> bool:
    """Whether this process signs and verifies envelopes."""
    return broker_key() is not None


def canonical_bytes(message: dict) -> bytes:
    """Render the envelope in the canonical form both sides sign."""
    body = {key: value for key, value in message.items() if key != SIG_FIELD}
    return json.dumps(
        body, sort_keys=True, separators=(",", ":"), ensure_ascii=False
    ).encode("utf-8")


def sign_envelope(envelope: dict) -> dict:
    """Return a copy of `envelope` carrying a fresh `sig`.

    Without a configured key this returns an unchanged copy: compatibility mode,
    in which nothing is signed and nothing is verified. The mode is logged where
    it matters (on verify), not on every publish.
    """
    signed = dict(envelope)
    signed.pop(SIG_FIELD, None)
    key = broker_key()
    if key is None:
        return signed
    signed[SIG_FIELD] = hmac.new(key, canonical_bytes(signed), hashlib.sha256).hexdigest()
    return signed


def verify_envelope_signature(message: dict) -> None:
    """Raise `EngineTaskContractError` unless `message` carries a valid `sig`.

    In compatibility mode (no key configured) this accepts anything, once with a
    warning: the alternative is bricking every stack that has not generated a key
    yet, and an unsigned envelope the operator chose to accept is not a forgery
    the operator failed to notice — the warning is what keeps the distinction.
    """
    from .engine_task_contract import EngineTaskContractError

    global _warned_compat
    key = broker_key()
    if key is None:
        if not _warned_compat:
            _warned_compat = True
            logger.warning(
                "broker_auth_compat reason=%s_not_configured "
                "unsigned_envelopes_are_accepted",
                KEY_ENV,
            )
        return
    presented = message.get(SIG_FIELD)
    if not isinstance(presented, str) or not presented:
        raise EngineTaskContractError("envelope is not signed (BAD_SIGNATURE)")
    expected = hmac.new(key, canonical_bytes(message), hashlib.sha256).hexdigest()
    if not hmac.compare_digest(presented, expected):
        raise EngineTaskContractError("envelope signature is invalid (BAD_SIGNATURE)")
