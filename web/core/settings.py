# SECRET_KEY signs session cookies and CSRF tokens, so a published value is a
# published signing key. The value below is generated once per installation and
# kept in `data/run/secret_key`, which is gitignored, so it survives restarts
# (a key that changed every boot would invalidate every open session) without
# ever being committed. `RR_SECRET_KEY` overrides it for an operator who keeps
# the secret somewhere else. This is the documented default the project rule
# allows: not a constant in the body of the loop, but a value visible in the
# environment and on disk.
_RR_SECRET_KEY_ENV = "RR_SECRET_KEY"
_RR_SECRET_KEY_FILE = Path(__file__).resolve().parent.parent.parent / "data" / "run" / "secret_key"


def _tighten_key_permissions(target):
    """Put the key directory and the key back to 0700/0600, if they exist.

    Called on every branch, including the environment one. `start.sh` documents
    `RR_SECRET_KEY` as the supported way to hold the key outside the repository,
    so the env branch is an ordinary operator configuration, not a corner case —
    and returning from it first left `data/run` at the umask's mode in precisely
    the configuration the documentation recommends. The file is not read when the
    key comes from the environment, but it can still exist from an earlier run,
    and a directory another local user can write is the thing this control is
    about. Best-effort: a read-only checkout has nothing to tighten.
    """
    try:
        target.parent.chmod(0o700)
        if target.exists():
            target.chmod(0o600)
    except OSError:
        pass


def _load_secret_key(key_file=None):
    """Return the Django signing key from the environment, disk, or a fresh CSPRNG.

    `key_file` exists for the tests: the permission fix below is about the
    directory around the key, and the only honest way to assert it is against a
    real directory whose mode this process created.
    """
    target = Path(key_file) if key_file is not None else _RR_SECRET_KEY_FILE
    from_env = os.environ.get(_RR_SECRET_KEY_ENV, "").strip()
    if from_env:
        _tighten_key_permissions(target)
        return from_env
    try:
        existing = target.read_text(encoding="utf-8").strip()
    except OSError:
        existing = ""
    if existing:
        # The file is protected, but the directory holding it may not be: the
        # stack creates `data/run` with the process umask, which on a default
        # shell is 022 — and the measured mode was 0777. Another local user who
        # can write that directory can delete the key and put their own in its
        # place, and from then on they mint session and CSRF cookies themselves.
        # Re-tightening on every load costs nothing and is idempotent.
        _tighten_key_permissions(target)
        return existing
    import secrets

    generated = secrets.token_urlsafe(64)
    try:
        target.parent.mkdir(parents=True, exist_ok=True)
        # 0700 on the directory, 0600 on the key: both are part of the same
        # control, and the mode the process umask happens to produce is not a
        # decision anybody made on purpose.
        target.parent.chmod(0o700)
        target.write_text(generated + "\n", encoding="utf-8")
        # The key is a signing key: readable by anyone who can read the file.
        target.chmod(0o600)
    except OSError:
        # A read-only checkout still has to run, and the key is only a
        # development convenience here. It is regenerated per boot in that case,
        # which costs the open sessions and nothing else — but the operator is
        # told, because a key that silently changes is a confusing failure.
        import sys

        print(
            f"warning: cannot persist the generated secret key to "
            f"{target}; sessions will not survive a restart",
            file=sys.stderr,
        )
    return generated


