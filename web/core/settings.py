# --- Logging ------------------------------------------------------------------
#
# WHY A FILE, AND NOT ONLY THE TERMINAL.
#
# Every `lab.*` record went to `StreamHandler` alone. Measured on a live stack: the
# console carries `intruder_start`, `project_save_failed`, `workflow_run_failed`,
# `engine_request_unavailable`, `engine_result_dead_lettered` and every 5xx traceback —
# and `data/logs/` held `engine.log`, `browser-worker.log`, `redis.log`,
# `postgres.log` and no `web.log` at all. So the gateway was the one service whose log
# vanished the moment the terminal was closed, and the claim in `AGENTS.md` that logs
# live in `data/logs`, one file per process, was false for the gateway specifically.
#
# WHY ROTATION. `engine.log`, `redis.log` and `browser-worker.log` are appended to
# without limit. An unbounded file is not a record, it is a liability: it grows until
# the disk is full, and the line an analyst wants — "the broker was unreachable for
# 3m14s" — never appears because the failure is one identical line per iteration.
# Rotation is what makes the file readable a month later.
#
# WHY 0600. These lines name hosts, slugs, project ids and durations. Nothing here is
# a payload body, which is the discipline the rest of the project follows; the mode
# keeps it that way for other local users. The file is opened in append mode so a
# restart adds to the record instead of replacing it.
#
# WHY THE CONSOLE STAYS. Redirecting instead of adding would be a silent behaviour
# change for anyone who watches the terminal during local QA, and this file exists to
# make a capability visible, not to take one away.
_RR_LOG_DIR = Path(__file__).resolve().parent.parent.parent / "data" / "logs"
_RR_WEB_LOG = _RR_LOG_DIR / "web.log"

