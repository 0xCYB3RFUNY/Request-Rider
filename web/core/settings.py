class _RestrictedRotatingFileHandler(logging.handlers.RotatingFileHandler):
    """Rotating handler that narrows the log file's mode the first time it opens it.

    Why a subclass rather than a `chmod` at import: `delay: True` means the file is
    not created until the first record, so a chmod at import has nothing to act on —
    and the measured result was `-rw-rw-r--`, the umask default, not the intended
    `0600`. Chmod-ing an existing file at import was equally wrong for the opposite
    reason: a log rotated away and recreated comes back at the umask mode, so the
    permission would silently regress on every rotation.

    Best-effort by design: logging must never be the reason a request fails. A
    filesystem that refuses the chmod is reported once on stderr and the console
    handler keeps working, because a readable log beats a correct mode.
    """

    _mode_warned = False

    def _open(self):
        stream = super()._open()
        try:
            name = getattr(stream, "name", None)
            if name:
                # `os.fchmod` closes the race with the log rotation renaming files:
                # chmod by name can hit a file this handler no longer owns.
                os.fchmod(stream.fileno(), 0o600)
        except (OSError, ValueError) as error:
            if not self._mode_warned:
                self._mode_warned = True
                import sys

                print(f"warning: could not narrow web log mode: {error}", file=sys.stderr)
        return stream


def _install_web_log_file():
    """Create `data/logs` before the handler can need it.

    `delay: True` means the file is not created at import, so the directory has to
    exist first or the first record after a fresh checkout would raise inside the
    logging machinery. Best-effort: a filesystem that refuses is reported on stderr
    and the console handler keeps working.
    """
    try:
        _RR_LOG_DIR.mkdir(parents=True, exist_ok=True)
    except OSError as error:
        import sys

        print(f"warning: web log directory unavailable: {error}", file=sys.stderr)


_install_web_log_file()
